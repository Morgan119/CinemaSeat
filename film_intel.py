def find_player(text):
    lowered = text.lower().replace("'", '’')
    hits = [item for name, item in PLAYERS.items() if name in lowered or name.split()[-1] in lowered.split()]
    hits.sort(key=lambda item: len(item['role']), reverse=True)
    exact = [item for name, item in PLAYERS.items() if name in lowered]
    return (exact or hits or [None])[0], (exact and next(name for name, item in PLAYERS.items() if item == exact[0]) or next((name for name, item in PLAYERS.items() if item == hits[0]), ''))

def find_film(text):
    lowered = text.lower()
    for key, film in FILMS.items():
        title = film['title'].lower()
        if key in lowered or title in lowered or any(word in lowered for word in title.replace(':', ' ').split() if len(word) > 3):
            return key, film
    for name, player in PLAYERS.items():
        if name in lowered:
            return player['film'], FILMS[player['film']]
    return None, None

